//! Virtio-Binder wire protocol definitions and packet framing.
//!
//! Conforms to Virtio ID 44 (`VIRTIO_ID_BINDER`) and 64-bit Android Binder IPC C-ABI.

use binder_rt::types::BinderSizeT;
use binder_rt::wire::{BR_OK, BR_REPLY, BR_TRANSACTION_COMPLETE, PING_TRANSACTION, TF_ONE_WAY};
use binder_rt::Parcel;
use bytemuck::{Pod, Zeroable};
use thiserror::Error;

/// OASIS / Custom Virtio Device ID for Paravirtualized Binder.
pub const VIRTIO_ID_BINDER: u32 = 44;

/// Virtqueue index 0: Bidirectional Request / Reply Queue.
pub const VIRTIO_BINDER_QUEUE_TX_RX: u16 = 0;

/// Virtqueue index 1: Host-to-Guest Asynchronous Event / Death Notification Queue.
pub const VIRTIO_BINDER_QUEUE_EVENT: u16 = 1;

// -----------------------------------------------------------------------------
// Virtio-Binder Command Constants
// -----------------------------------------------------------------------------

/// Perform an IPC transaction against a target handle.
pub const CMD_TRANSACT: u32 = 1;

/// Increment strong reference count for a target handle.
pub const CMD_ACQUIRE: u32 = 2;

/// Decrement strong reference count for a target handle.
pub const CMD_RELEASE: u32 = 3;

/// Link death notification recipient to a target handle.
pub const CMD_LINK_DEATH: u32 = 4;

/// Unlink death notification recipient from a target handle.
pub const CMD_UNLINK_DEATH: u32 = 5;

/// Ping remote handle or host service manager.
pub const CMD_PING: u32 = 6;

// -----------------------------------------------------------------------------
// Virtio-Binder Event Type Constants
// -----------------------------------------------------------------------------

/// Death notification for a host service.
pub const EVENT_TYPE_DEATH: u32 = 1;

/// Acquire reference notification.
pub const EVENT_TYPE_ACQUIRE: u32 = 2;

/// Release reference notification.
pub const EVENT_TYPE_RELEASE: u32 = 3;

// -----------------------------------------------------------------------------
// Protocol Errors
// -----------------------------------------------------------------------------

/// Errors occurring during Virtio-Binder packet serialization or deserialization.
#[derive(Debug, Error, PartialEq, Eq, Clone)]
pub enum ProtocolError {
    #[error("Packet too short: expected at least {expected} bytes, found {actual}")]
    PacketTooShort { expected: usize, actual: usize },

    #[error("Payload size mismatch: data_size ({data_size}) + offsets_size ({offsets_size}) > remaining payload ({remaining})")]
    PayloadSizeMismatch {
        data_size: usize,
        offsets_size: usize,
        remaining: usize,
    },

    #[error("Offsets size {0} is not a multiple of sizeof(BinderSizeT) (8 bytes)")]
    InvalidOffsetsSize(usize),

    #[error("Unknown or invalid command opcode: {0}")]
    InvalidCommand(u32),

    #[error("Parcel conversion error: {0}")]
    ParcelConversionError(String),
}

// -----------------------------------------------------------------------------
// Request Header: VirtioBinderReqHdr
// -----------------------------------------------------------------------------

/// 48-byte 64-bit C-ABI Request Header for Virtio-Binder transactions.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Pod, Zeroable, Default)]
pub struct VirtioBinderReqHdr {
    /// Unique transaction sequence number generated by guest transport.
    pub msg_id: u64,
    /// Command opcode (`CMD_TRANSACT`, `CMD_ACQUIRE`, `CMD_RELEASE`, etc.).
    pub cmd: u32,
    /// Target Binder handle ID (0 for ServiceManager).
    pub target_handle: u32,
    /// AIDL Transaction code (e.g., 1, 2, `PING_TRANSACTION`).
    pub code: u32,
    /// Transaction flags (`TF_ONE_WAY`, etc.).
    pub flags: u32,
    /// Sender cookie / tracking token.
    pub cookie: u64,
    /// Length of following Parcel payload in bytes.
    pub data_size: u32,
    /// Length of offsets array in bytes (`count * 8`).
    pub offsets_size: u32,
    /// Alignment padding.
    pub padding: u32,
    /// Reserved field for 8-byte alignment.
    pub _reserved: u32,
}

impl VirtioBinderReqHdr {
    /// Construct a new transaction request header.
    #[allow(clippy::too_many_arguments)]
    pub const fn new_transact(
        msg_id: u64,
        target_handle: u32,
        code: u32,
        flags: u32,
        cookie: u64,
        data_size: u32,
        offsets_size: u32,
    ) -> Self {
        Self {
            msg_id,
            cmd: CMD_TRANSACT,
            target_handle,
            code,
            flags,
            cookie,
            data_size,
            offsets_size,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Construct a new ping request header.
    pub const fn new_ping(msg_id: u64, target_handle: u32) -> Self {
        Self {
            msg_id,
            cmd: CMD_PING,
            target_handle,
            code: PING_TRANSACTION,
            flags: 0,
            cookie: 0,
            data_size: 0,
            offsets_size: 0,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Construct a new acquire reference request header.
    pub const fn new_acquire(msg_id: u64, target_handle: u32) -> Self {
        Self {
            msg_id,
            cmd: CMD_ACQUIRE,
            target_handle,
            code: 0,
            flags: 0,
            cookie: 0,
            data_size: 0,
            offsets_size: 0,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Construct a new release reference request header.
    pub const fn new_release(msg_id: u64, target_handle: u32) -> Self {
        Self {
            msg_id,
            cmd: CMD_RELEASE,
            target_handle,
            code: 0,
            flags: 0,
            cookie: 0,
            data_size: 0,
            offsets_size: 0,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Construct a new link death request header.
    pub const fn new_link_death(msg_id: u64, target_handle: u32, cookie: u64) -> Self {
        Self {
            msg_id,
            cmd: CMD_LINK_DEATH,
            target_handle,
            code: 0,
            flags: 0,
            cookie,
            data_size: 0,
            offsets_size: 0,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Construct a new unlink death request header.
    pub const fn new_unlink_death(msg_id: u64, target_handle: u32, cookie: u64) -> Self {
        Self {
            msg_id,
            cmd: CMD_UNLINK_DEATH,
            target_handle,
            code: 0,
            flags: 0,
            cookie,
            data_size: 0,
            offsets_size: 0,
            padding: 0,
            _reserved: 0,
        }
    }

    /// Return true if this is an asynchronous one-way transaction.
    pub const fn is_one_way(&self) -> bool {
        (self.flags & TF_ONE_WAY) != 0
    }

    /// Return raw byte slice representation.
    pub fn as_bytes(&self) -> &[u8] {
        bytemuck::bytes_of(self)
    }

    /// Parse header from byte slice.
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, ProtocolError> {
        let hdr_size = std::mem::size_of::<Self>();
        if bytes.len() < hdr_size {
            return Err(ProtocolError::PacketTooShort {
                expected: hdr_size,
                actual: bytes.len(),
            });
        }
        let mut hdr_bytes = [0u8; std::mem::size_of::<Self>()];
        hdr_bytes.copy_from_slice(&bytes[..hdr_size]);
        let hdr: Self = bytemuck::pod_read_unaligned(&hdr_bytes);
        Ok(hdr)
    }
}

