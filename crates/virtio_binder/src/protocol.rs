/// 32-byte 64-bit C-ABI Response Header for Virtio-Binder transactions.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Pod, Zeroable, Default)]
pub struct VirtioBinderRespHdr {
    /// Matching transaction sequence number.
    pub msg_id: u64,
    /// Binder kernel status code (0 = `STATUS_OK`, `<0` = error).
    pub status: i32,
    /// Return code (`BR_REPLY`, `BR_DEAD_REPLY`, `BR_TRANSACTION_COMPLETE`, `BR_FAILED_REPLY`).
    pub result_code: i32,
    /// Length of response Parcel payload in bytes.
    pub data_size: u32,
    /// Length of response offsets array in bytes.
    pub offsets_size: u32,
    /// Response flags.
    pub flags: u32,
    /// Alignment padding.
    pub padding: u32,
}

impl VirtioBinderRespHdr {
    /// Construct a new response header.
    pub const fn new(
        msg_id: u64,
        status: i32,
        result_code: i32,
        data_size: u32,
        offsets_size: u32,
        flags: u32,
    ) -> Self {
        Self {
            msg_id,
            status,
            result_code,
            data_size,
            offsets_size,
            flags,
            padding: 0,
        }
    }

    /// Construct a success response header (`STATUS_OK` / `BR_REPLY`).
    pub const fn new_ok(msg_id: u64, data_size: u32, offsets_size: u32) -> Self {
        Self::new(
            msg_id,
            binder_rt::status::STATUS_OK,
            BR_REPLY as i32,
            data_size,
            offsets_size,
            0,
        )
    }

    /// Construct an asynchronous completion response header (`BR_TRANSACTION_COMPLETE`).
    pub const fn new_one_way_complete(msg_id: u64) -> Self {
        Self::new(
            msg_id,
            binder_rt::status::STATUS_OK,
            BR_TRANSACTION_COMPLETE as i32,
            0,
            0,
            0,
        )
    }

    /// Construct an error response header.
    pub const fn new_error(msg_id: u64, status: i32, result_code: i32) -> Self {
        Self::new(msg_id, status, result_code, 0, 0, 0)
    }

    /// Return true if the transaction succeeded.
    pub const fn is_success(&self) -> bool {
        self.status == binder_rt::status::STATUS_OK
            && (self.result_code == BR_REPLY as i32
                || self.result_code == BR_TRANSACTION_COMPLETE as i32
                || self.result_code == BR_OK as i32)
    }

    /// Return raw byte slice representation.
    pub fn as_bytes(&self) -> &[u8] {
        bytemuck::bytes_of(self)
    }

    /// Parse header from byte slice.
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, ProtocolError> {
        let hdr_size = std::mem::size_of::<Self>();
        if bytes.len() < hdr_size {
            return Err(ProtocolError::PacketTooShort {
                expected: hdr_size,
                actual: bytes.len(),
            });
        }
        let mut hdr_bytes = [0u8; std::mem::size_of::<Self>()];
        hdr_bytes.copy_from_slice(&bytes[..hdr_size]);
        let hdr: Self = bytemuck::pod_read_unaligned(&hdr_bytes);
        Ok(hdr)
    }
}

